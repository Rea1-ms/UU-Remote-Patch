let rendered = '\n';
let total = 0;
for (const [file, sections] of specs) {
  const bytes = await fs.readFile(path.join(root, file));
  const lines = bytes.toString('utf8').replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n');
  const located = sections.map(([anchor, title, explanation]) => {
    const matches = anchor === '' ? [0] : lines.flatMap((line, i) => line.startsWith(anchor) ? [i] : []);
    if (matches.length !== 1) throw Error(`${file}: anchor must be unique: ${anchor}`);
    return { start: matches[0], title, explanation };
  });
  if (located[0].start !== 0 || located.some((section, i) => i && section.start <= located[i-1].start))
    throw Error(`${file}: source sections must be ordered and cover line one`);
  const digest = crypto.createHash('sha256').update(lines.join('\n')+'\n').digest('hex');
  rendered += `## ${file}（源码文件）\n\n共 ${lines.length} 行；SHA-256（按换行归一化的安全摘要）：\`${digest}\`。\n\n`;
  for (let i = 0; i < located.length; ++i) {
    const section = located[i], end = located[i+1]?.start ?? lines.length;
    rendered += `### 第 ${section.start+1} 至 ${end} 行：${section.title}\n\n${section.explanation}\n\n`;
    rendered += '```text\n' + lines.slice(section.start, end).map((line, n) => `${String(section.start+n+1).padStart(4)} |${line?' '+line:''}`).join('\n') + '\n```\n\n';
  }
  total += lines.length;
}
const documentPath = path.join(root, 'docs/实现详解.md');
const current = await fs.readFile(documentPath, 'utf8');
const begin = '<!-- source-explanation:start -->', end = '<!-- source-explanation:end -->';
const first = current.indexOf(begin), last = current.indexOf(end);
if (first < 0 || last < first || current.indexOf(begin, first+1) >= 0 || current.indexOf(end, last+1) >= 0)
  throw Error('Expected exactly one source explanation region');
const expected = current.slice(0, first+begin.length) + '\n' + rendered + current.slice(last);
if (process.argv.includes('--write')) await fs.writeFile(documentPath, expected);
else if (process.argv.includes('--check')) {
  if (current !== expected) throw Error('Source explanation is stale; update section explanations and run --write');
} else throw Error('Use --write or --check');
console.log(`Checked ${specs.length} source files, ${total} numbered lines.`);
